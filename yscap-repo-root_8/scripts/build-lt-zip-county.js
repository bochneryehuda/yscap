#!/usr/bin/env node
'use strict';
/**
 * GENERATOR — builds the LT Lender Price ZIP → county dataset from the U.S. Census Bureau's own
 * ZCTA-to-county relationship file. Run by hand when the Census publishes a new vintage; the output
 * (src/longterm/lenderprice/zip-county.json) is committed so the PRICING PATH never touches the
 * network or a database.
 *
 * WHY A GENERATED TABLE rather than a geocoder call per quote:
 *   • Pricing is ZIP-driven (the vendor's own screen takes a 5-digit ZIP and fills state + county),
 *     and the Census ADDRESS geocoder cannot answer a bare ZIP at all — it matches address ranges.
 *   • A quote must not depend on an outside service being up, and must stay offline-testable.
 *   • The data is federal, public, versioned and stable between vintages.
 *
 * PINNED (the repo's "pin your tools" rule): the source URL, the vintage and the SHA-256 of the file
 * this was built from are recorded in the output, so the exact input is reproducible and a silently
 * changed upstream file is detectable.
 *
 *   node scripts/build-lt-zip-county.js [path-to-relationship-file]
 *     (with no argument it downloads SOURCE_URL to a temp file)
 *
 * LT-only. Writes one file; reads no database.
 */
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');

const SOURCE_URL = 'https://www2.census.gov/geo/docs/maps-data/data/rel2020/zcta520/tab20_zcta520_county20_natl.txt';
const VINTAGE = '2020';
const OUT = path.join(__dirname, '..', 'src', 'longterm', 'lenderprice', 'zip-county.json');

// Column positions in the pipe-delimited relationship file (header row names them in full).
const C_ZCTA = 1;        // GEOID_ZCTA5_20      — the 5-digit ZCTA
const C_COUNTY = 9;      // GEOID_COUNTY_20     — the 5-digit county FIPS (state 2 + county 3)
const C_COUNTY_NAME = 10; // NAMELSAD_COUNTY_20 — e.g. "Kings County"
const C_LAND_PART = 16;  // AREALAND_PART       — land area of the ZCTA∩county overlap

async function readSource(arg) {
  if (arg && fs.existsSync(arg)) return fs.readFileSync(arg);
  const res = await fetch(SOURCE_URL);
  if (!res.ok) throw new Error(`Census download failed: HTTP ${res.status}`);
  return Buffer.from(await res.arrayBuffer());
}

function build(buf) {
  const sha256 = crypto.createHash('sha256').update(buf).digest('hex');
  const lines = buf.toString('utf8').split('\n');
  /** @type {Map<string, Array<{fips:string,name:string,land:number}>>} */
  const byZip = new Map();
  for (let i = 1; i < lines.length; i++) {
    const f = lines[i].split('|');
    if (f.length < 18) continue;
    const zip = (f[C_ZCTA] || '').trim();
    const fips = (f[C_COUNTY] || '').trim();
    if (!/^\d{5}$/.test(zip) || !/^\d{5}$/.test(fips)) continue; // county-only rows carry no ZCTA
    const land = Number(f[C_LAND_PART] || 0);
    const name = (f[C_COUNTY_NAME] || '').trim();
    if (!byZip.has(zip)) byZip.set(zip, []);
    byZip.get(zip).push({ fips, name, land: Number.isFinite(land) ? land : 0 });
  }

  // One entry per county, referenced by index, so a county name is stored once rather than ~10x.
  const countyIndex = new Map(); // fips -> index
  const counties = [];           // "fips|Name"
  const idxOf = (fips, name) => {
    if (!countyIndex.has(fips)) { countyIndex.set(fips, counties.length); counties.push(`${fips}|${name}`); }
    return countyIndex.get(fips);
  };

  const zips = [];
  let split = 0;
  for (const zip of [...byZip.keys()].sort()) {
    const parts = byZip.get(zip).slice().sort((a, b) => b.land - a.land); // dominant by land area first
    const top = parts[0];
    // A ZIP genuinely spanning more than one county is FLAGGED, not hidden: the caller is told the
    // county was inferred so they can override it with an explicit countyFps. A sliver overlap
    // (>=99% of the ZIP's land in one county) is a boundary artifact, not a real split.
    const total = parts.reduce((n, p) => n + p.land, 0) || 1;
    const isSplit = parts.length > 1 && (top.land / total) < 0.99;
    if (isSplit) split++;
    zips.push(`${zip}${String(idxOf(top.fips, top.name)).padStart(4, '0')}${isSplit ? '1' : '0'}`);
  }

  return {
    _comment: 'GENERATED by scripts/build-lt-zip-county.js — do not hand-edit. ZIP -> dominant county for LT Lender Price pricing.',
    source: SOURCE_URL,
    vintage: VINTAGE,
    sourceSha256: sha256,
    builtFormat: 'zips[] = zip(5) + countyRef(4, index into counties) + splitFlag(1); counties[] = "fips|NAMELSAD"',
    zipCount: zips.length,
    countyCount: counties.length,
    splitZipCount: split,
    counties,
    zips: zips.join(''),
  };
}

async function main() {
  const buf = await readSource(process.argv[2]);
  const out = build(buf);
  fs.writeFileSync(OUT, JSON.stringify(out));
  const kb = (fs.statSync(OUT).size / 1024).toFixed(0);
  console.log(`wrote ${path.relative(path.join(__dirname, '..'), OUT)} — ${out.zipCount} ZIPs, ${out.countyCount} counties, ${out.splitZipCount} split (${kb} KB)`);
  console.log(`source sha256 ${out.sourceSha256}`);
}
main().catch((e) => { console.error(e.message); process.exit(1); });
