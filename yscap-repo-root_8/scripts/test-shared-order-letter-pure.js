'use strict';
/**
 * THE ORDER LETTER IS SHARED, NOT COPIED — and the two products' reply addresses
 * can never be mistaken for each other.
 *
 * Two things shipped on 2026-08-30 so the long-term orders desk could use the
 * short-term desk's letter instead of growing a second one (the owner: *"Everything
 * should share the code, so we don't need to rewrite the code … If the code is
 * updated, he's also updating it"* — and, in the same breath, *"watch what you're
 * doing not to break the other side of the business"*):
 *
 *   · `src/lib/order-email.js`  — the letter, the clause, the recipient rule, the
 *     threading headers and the send verdict, lifted out of `src/lib/orders.js`,
 *     which now re-exports them.
 *   · `src/lib/inbound-mail.js` — the provider-facing half of the inbox, lifted out
 *     of `src/lib/file-inbox.js`, which now re-exports them.
 *
 * WHAT THIS SUITE IS FOR. A behaviour test on the short-term desk would pass just as
 * happily against a second COPY of the letter living in the long-term folder — which
 * is the failure the owner asked to avoid, and it is silent: both copies work, and
 * they drift on the first edit. So the assertions here are about IDENTITY (the same
 * function object reached from both doors), about PURITY (the shared modules can
 * never drag a database pool into whichever product imports them), and about the one
 * thing sharing an inbound domain makes newly possible — two address families
 * colliding in a single namespace.
 *
 * PURE: no database, no network. Nothing here sends anything.
 */
const assert = require('assert');
const fs = require('fs');
const path = require('path');

process.env.CHAT_REPLY_DOMAIN = process.env.CHAT_REPLY_DOMAIN || 'orders.yscapgroup.example';

const root = path.join(__dirname, '..');
const read = (p) => fs.readFileSync(path.join(root, p), 'utf8');
let n = 0;
const ok = (m) => { n++; console.log('  ok -', m); };

const orderEmail = require('../src/lib/order-email');
const orders = require('../src/lib/orders');
const closingHandling = require('../src/lib/closing-handling');
const fileAddress = require('../src/lib/file-address');
const inboundMail = require('../src/lib/inbound-mail');
const fileInbox = require('../src/lib/file-inbox');

/* ─────────────────────────────────────────────────────────────────────────────
   A. ONE DEFINITION — the same function object, reached from both doors.

   `===` is the assertion that matters. A re-export that happened to be a copy
   with identical behaviour would satisfy any output comparison and would still be
   the second definition this whole change exists to prevent.
   ───────────────────────────────────────────────────────────────────────────── */
const SHARED_FROM_ORDERS = [
  'ORDER_TYPES', 'VENDOR_TYPE', 'ORDER_LABEL',
  'MORTGAGEE_CLAUSE', 'MORTGAGEE_CLAUSE_RCN',
  'INSURANCE_COVERAGE_LINES', 'insuranceDetailMeta',
  'money', 'dayText', 'transactionType', 'propertyLine', 'vendorEmails',
  'ccBorrowerSettingKey', 'ccBorrowerDefault', 'ccHelperSettingKey', 'ccHelperDefault',
  'helperEmails', 'recipientsFor',
  'sendVerdict', 'isAmbiguousSendFailure', 'newOrderMessageId', 'replyOrderSubject',
];
for (const k of SHARED_FROM_ORDERS) {
  assert.ok(orderEmail[k] !== undefined, `order-email exports ${k}`);
  assert.strictEqual(orders[k], orderEmail[k], `lib/orders re-exports the SAME ${k} (not a copy)`);
}
ok(`the short-term desk re-exports all ${SHARED_FROM_ORDERS.length} shared order names as the same objects`);

for (const k of ['NY_TITLE_CUT', 'TITLE_WANTS_FULL', 'isNyState', 'titleWants']) {
  assert.strictEqual(closingHandling[k], orderEmail[k], `closing-handling re-exports the SAME ${k}`);
}
ok('the New-York title cut has one definition, shared by the letter and the closing desk');

const SHARED_FROM_INBOX = [
  'recipientsFromEvent', 'retrieveInboundEmail', 'retrieveAttachmentsSafe',
  'inboundKey', 'isAutoGenerated', 'extractAddress',
];
for (const k of SHARED_FROM_INBOX) {
  assert.ok(typeof inboundMail[k] === 'function', `inbound-mail exports ${k}`);
  assert.strictEqual(fileInbox[k], inboundMail[k], `file-inbox re-exports the SAME ${k} (not a copy)`);
}
assert.strictEqual(fileInbox._internals.senderAuth, inboundMail.senderAuth, 'file-inbox re-exports the SAME senderAuth');
ok('the short-term inbox re-exports the shared reading as the same objects');

/* ─────────────────────────────────────────────────────────────────────────────
   B. PURITY — a shared module may never drag a product's data layer with it.

   This is the whole reason `lib/orders.js` itself could not be shared: it requires
   the short-term pool at module load, so importing it from the long-term side would
   not be sharing code, it would be one product running on the other's data layer.
   If either shared module ever grows a pool require, the crossing stops being legal
   and nothing else in the build would say so.
   ───────────────────────────────────────────────────────────────────────────── */
const BANNED_REQUIRE = /require\(\s*['"](\.\.\/db|\.\/db|\.\.\/longterm\/db|\.\.\/\.\.\/db)['"]\s*\)/;
/* COMMENTS ARE STRIPPED FIRST. Each of these files necessarily NAMES the require it
   must not have — that is how a header explains why the module is shareable — so a
   guard that read the prose would fail on its own explanation and then be "fixed" by
   loosening it. Read the code. */
const codeOnly = (src) => src.replace(/\/\*[\s\S]*?\*\//g, '').replace(/(^|[^:])\/\/[^\n]*/g, '$1');
for (const f of ['src/lib/order-email.js', 'src/lib/inbound-mail.js', 'src/lib/file-address.js',
  'src/lib/email/template.js', 'src/lib/email/quote.js']) {
  const src = codeOnly(read(f));
  assert.ok(!BANNED_REQUIRE.test(src), `${f} requires no database pool`);
  assert.ok(!/require\(\s*['"]\.\.\/longterm/.test(src), `${f} does not reach into the long-term product`);
}
ok('every module the long-term desk is authorized to import is free of a database pool');

// And the two shared modules genuinely LOAD with no DATABASE_URL in reach — the
// require above already proved it for this process, so state it as the property.
assert.ok(typeof orderEmail.buildOrderEmail === 'function' && typeof inboundMail.retrieveInboundEmail === 'function',
  'both shared modules load standalone');
ok('both shared modules load with no database configured');

/* ─────────────────────────────────────────────────────────────────────────────
   C. THE TWO RULES THE BUILDER DELIBERATELY DOES NOT DECIDE.

   The mortgagee clause and the reply address are INPUTS. The short-term desk states
   both on every call; the long-term desk states its own. A default that quietly
   applied one product's answer to the other product's order is the failure mode.
   ───────────────────────────────────────────────────────────────────────────── */
const LOAN = '11111111-2222-3333-4444-555555555555';
const data = {
  appId: LOAN, loanNumber: 'YSCAP258134650', hasLoanNumber: true,
  propertyLine: '129 Carlisle St, Wilkes-Barre, PA 18702', propertyState: 'PA',
  borrowerName: 'Test Borrower', borrowerEmail: 'b@example.com',
  loanAmount: '$400,000', lender: 'RCN Capital, LLC',
  officer: { name: 'A Officer', title: 'Loan Officer', email: 'lo@example.com' },
  processor: { email: 'proc@example.com' },
  vendors: { title: { company_name: 'A Title Co', email: 'title@example.com' }, insurance: { email: 'ins@example.com' } },
  vendorsExtra: {}, helpers: [],
};

// The bare builder never guesses a note buyer's servicer clause off a name it
// cannot read: with no clause stated it prints the company's standard one.
const bare = orderEmail.buildOrderEmail('title', data, {});
assert.ok(bare.text.includes('5 New Montrose Avenue'), 'an unstated clause is the standard company clause');
assert.ok(!bare.text.includes('Elite Commercial Servicing'), 'the bare builder never infers a servicer clause');
// The short-term desk states the RCN servicer clause on an RCN file — unchanged.
const rtl = orders.buildOrderEmail('title', data, {});
assert.ok(rtl.text.includes('Elite Commercial Servicing'), 'the short-term desk still states the RCN servicer clause');
// A caller may state any clause, and it is what prints.
const stated = orderEmail.buildOrderEmail('title', data, { mortgageeClause: ['Somebody Else, ISAOA', 'PO Box 1'] });
assert.ok(stated.text.includes('Somebody Else, ISAOA') && !stated.text.includes('5 New Montrose Avenue'),
  'a stated clause replaces the default outright');
ok('the mortgagee clause is an input: unstated → standard, short-term desk → RCN-aware, stated → verbatim');

const rtlRecips = orderEmail.recipientsFor('title', data, {});
assert.strictEqual(rtlRecips.replyTo, `title+${LOAN}@${process.env.CHAT_REPLY_DOMAIN}`, 'default reply address is the short-term family');
const ltRecips = orderEmail.recipientsFor('title', data, { replyTo: fileAddress.ltOrderReplyTo(LOAN, 'title') });
assert.strictEqual(ltRecips.replyTo, `ltorder+title.${LOAN}@${process.env.CHAT_REPLY_DOMAIN}`, 'a stated reply address is used verbatim');
assert.deepStrictEqual(ltRecips.to, rtlRecips.to, 'stating a reply address changes nothing else about the recipients');
assert.deepStrictEqual(ltRecips.cc, rtlRecips.cc, 'stating a reply address changes nothing else about the Cc');
ok('the reply address is an input, and stating it moves nothing else');

/* ─────────────────────────────────────────────────────────────────────────────
   D. ONE INBOUND DOMAIN, ONE NAMESPACE — the families are mutually exclusive.

   This is the collision the whole `ltorder+` family exists to prevent. A long-term
   order that reused `title+<uuid>@` would be parsed by the short-term router, looked
   up against the short-term table, found to be nothing, and ACKNOWLEDGED — so the
   vendor's reply and every document on it would be dropped in silence.

   Asserted in BOTH directions, because either half alone leaves the other armed.
   ───────────────────────────────────────────────────────────────────────────── */
const rtlAddr = fileAddress.orderReplyTo(LOAN, 'title');
const ltAddr = fileAddress.ltOrderReplyTo(LOAN, 'title');
assert.notStrictEqual(rtlAddr, ltAddr, 'the two families mint different addresses for the same id');
assert.strictEqual(fileAddress.orderRefFromRecipient(ltAddr), null, 'the short-term router cannot claim a long-term order address');
assert.strictEqual(fileAddress.ltOrderRefFromRecipient(rtlAddr), null, 'the long-term router cannot claim a short-term order address');
for (const other of [fileAddress.fileReplyTo(LOAN), fileAddress.rvReplyTo(LOAN), fileAddress.closingReplyTo('a'.repeat(20))]) {
  assert.strictEqual(fileAddress.ltOrderRefFromRecipient(other), null, `the long-term router cannot claim ${String(other).split('+')[0]}+`);
}
assert.strictEqual(fileAddress.applicationIdFromRecipient(ltAddr), null, 'the file-forward router cannot claim it either');
ok('the long-term order address is exclusive to its own router, both ways');

// The kind is part of the local part, and it round-trips. A malformed kind or id
// mints nothing rather than an address the router would then mis-read.
for (const kind of ['title', 'insurance', 'flood_insurance', 'ny_settlement', 'appraisal', 'payoff', 'vor']) {
  const a = fileAddress.ltOrderReplyTo(LOAN, kind);
  assert.deepStrictEqual(fileAddress.ltOrderRefFromRecipient(a), { loanId: LOAN, orderKind: kind }, `${kind} round-trips`);
  assert.deepStrictEqual(fileAddress.ltOrderRefFromRecipient(a.toUpperCase()), { loanId: LOAN, orderKind: kind }, `${kind} round-trips case-insensitively`);
}
// A kind is normalised (trimmed + lower-cased) before it is judged, so 'Title'
// is a legitimate way to say 'title' and round-trips; these are the shapes that
// genuinely cannot be part of a local part.
assert.strictEqual(fileAddress.ltOrderReplyTo(LOAN, '  TITLE '), `ltorder+title.${LOAN}@${process.env.CHAT_REPLY_DOMAIN}`,
  'a kind is normalised, not refused, for case and padding');
for (const bad of ['', null, 'ny-settlement', 'a', 'x'.repeat(30), 'title.extra', 'ti tle', 'title1']) {
  assert.strictEqual(fileAddress.ltOrderReplyTo(LOAN, bad), null, `a malformed kind (${JSON.stringify(bad)}) mints nothing`);
}
for (const bad of ['', null, 'not-a-uuid', LOAN + 'x']) {
  assert.strictEqual(fileAddress.ltOrderReplyTo(bad, 'title'), null, 'a malformed loan id mints nothing');
}
ok('every long-term order kind round-trips, and a malformed kind or id mints nothing');

// A wrong DOMAIN is refused — the families are dormant off our own inbound domain.
assert.strictEqual(fileAddress.ltOrderRefFromRecipient(`ltorder+title.${LOAN}@somewhere-else.example`), null,
  'an address on another domain is never claimed');
ok('an address on another domain is never claimed');

/* ─────────────────────────────────────────────────────────────────────────────
   E. THE SOURCE STILL SAYS WHERE THE DEFINITION LIVES.

   A future edit that re-inlined the letter into `lib/orders.js` would pass every
   behaviour assertion above on the short-term side while quietly leaving the
   long-term desk on a stale copy. These two read the source because no runtime
   check can see it.
   ───────────────────────────────────────────────────────────────────────────── */
const ordersSrc = read('src/lib/orders.js');
assert.ok(/require\(\s*'\.\/order-email'\s*\)/.test(ordersSrc), 'lib/orders builds its letter from the shared module');
assert.ok(!/function buildOrderEmail\(kind, data, \{ followup/.test(ordersSrc),
  'the letter body is not re-inlined in lib/orders');
const inboxSrc = read('src/lib/file-inbox.js');
assert.ok(/require\(\s*'\.\/inbound-mail'\s*\)/.test(inboxSrc), 'file-inbox reads its messages through the shared module');
assert.ok(!/async function retrieveAttachmentsSafe\(/.test(inboxSrc), 'the retrieval is not re-inlined in file-inbox');
ok('neither definition has been re-inlined into the product-specific desk');

/* ── THE OWNER'S TITLE ASK IS ALL SEVEN ITEMS ────────────────────────────────
   Owner-directed 2026-08-30: the drafts in docs/longterm/OWNER-ORDER-DRAFTS.md list
   seven title deliverables and the code asked for five. The owner chose to apply the
   two missing ones to BOTH products, so this assertion guards the SHARED list — the
   whole point of one title letter is that neither product quietly grows its own ask. */
const oe = require('../src/lib/order-email');
const full = oe.titleWants('NJ');
for (const want of ['Title Commitment', 'CPL', 'Settlement agent E&O Insurance', 'Tax Certificate',
  'Wiring Instructions', 'Preliminary Settlement Statement']) {
  assert.ok(full.includes(want), `a non-NY title order asks for ${want}`);
}
// The survey ask is deliberately an EITHER/OR: on a great many files no survey exists
// and the correct answer is the affidavit or endorsement saying so. An ask worded only
// "Survey" gets silence on those files, so the alternative must survive in the text.
const survey = full.find((w) => /^Survey/.test(w));
assert.ok(survey && /no survey is required/.test(survey) && /Affidavit or Endorsement/.test(survey),
  `the survey ask offers the no-survey alternative: ${survey}`);
assert.strictEqual(full.length, 7, 'the non-NY title ask is exactly the owner\'s seven items');
ok('the shared title ask is the owner\'s full seven-item list');

/* ── AND NEW YORK STILL CUTS THE SETTLEMENT AGENT'S ITEMS ────────────────────
   In New York title does not settle, so the four items the SETTLEMENT AGENT owns
   never appear on a New-York title order. The E&O joined that cut when it joined the
   list (it is the settlement agent's own certificate). The CPL stays cut and is NOT
   reassigned: New York uses an Agent Authorization letter in lieu of a CPL
   (underwriting/investor-guidelines/corrfirst-fnf-spec.js:108), so on a NY file there
   is no CPL for anyone to produce. */
const ny = oe.titleWants('NY');
for (const cut of ['CPL', 'Wiring Instructions', 'Preliminary Settlement Statement', 'Settlement agent E&O Insurance']) {
  assert.ok(!ny.includes(cut), `a New-York title order never asks title for ${cut}`);
}
assert.deepStrictEqual(ny.filter((w) => !/^Survey/.test(w)), ['Title Commitment', 'Tax Certificate'],
  'what remains on a NY title order is the commitment and the tax certificate (plus the survey ask)');
assert.ok(ny.some((w) => /^Survey/.test(w)), 'the survey ask survives in New York — a survey is title\'s, not the settler\'s');
ok('the New-York cut still removes every settlement-agent item, and only those');

console.log(`\ntest-shared-order-letter-pure: ${n} checks passed`);
