'use strict';

// =============================================================================
// BUILD THE TEST-IMPACT MAP — run every test with the probe, record what it touched
// =============================================================================
//
// The baseline run. Runs every step of `npm test` under `ci-deps-probe.js` and
// writes `docs/ci/test-deps.json`: for each test, the repository files it
// actually read or required.
//
// RUN IT WITH A DATABASE. Every `*-db.js` suite self-skips without DATABASE_URL,
// and a skipped test touches almost nothing — its recorded list would be tiny
// and it would then be selected almost never. That is the one way this whole
// mechanism could quietly stop testing something. Two defences, and they are
// both needed:
//   • This builder REFUSES to write a map built without a database.
//   • And even with one, `ci-scope.js` treats a test with no recorded
//     dependencies as ALWAYS RUN, so an under-recorded test is over-tested
//     rather than skipped.
//
// THIS MAP IS MAINTAINED BY HAND. NOTHING REBUILDS IT ON A CADENCE.
//
// An earlier version of this comment said the map "is regenerated by the
// scheduled full run". That was never true and it cost the repository a
// morning: `.github/workflows/test.yml` has a nightly cron, but its four jobs
// are `test`, `test-db`, `schema-push` and `deploy` and NONE of them runs this
// builder or commits the map back. The only caller anywhere is the manual
// `npm run ci:deps` in package.json.
//
// So the map was built once on 2026-08-16 and left. On 2026-08-31 it crossed
// MAX_MAP_AGE_DAYS (14) and `test-ci-scope-pure.js` went red on every open pull
// request at once, on a file none of them had touched.
//
// WHAT TO DO ABOUT IT, until somebody schedules this:
//   • Run it by hand roughly every ten days: `npm run ci:deps` with a
//     DATABASE_URL pointing at a database these migrations built.
//   • `ci-scope.mapAgeWarning` prints a warning from day 10, so a run whose
//     log says the map is ageing is telling you to do exactly that.
//
// A guard whose documentation describes a cadence it does not have is worse
// than one that admits it is manual. If this is ever automated, the rebuild
// runs the WHOLE suite one test at a time — about two hours — so a nightly
// cadence would cost ~3,600 minutes a month against a 2,000-minute allowance.
// Weekly (~520) is the only cadence that fits, and the job that rebuilds must
// not be the job that holds the write grant (see `ci-schema-commit.js`).
//
// Usage:  DATABASE_URL=postgres://…  node scripts/ci-deps-build.js [--jobs N]

const fs = require('fs');
const os = require('os');
const path = require('path');
const { spawnSync } = require('child_process');
const { allSteps } = require('./ci-test-plan');

const ROOT = path.join(__dirname, '..');
const OUT_DIR = path.join(ROOT, 'docs', 'ci');
const OUT_FILE = path.join(OUT_DIR, 'test-deps.json');
const PROBE = path.join(__dirname, 'ci-deps-probe.js');

/** The script file a step runs, e.g. "node scripts/test-foo.js" -> "test-foo.js". */
function scriptOf(step) {
  const m = String(step).match(/scripts\/([\w.-]+\.(?:js|mjs))/);
  return m ? m[1] : null;
}

function runOne(step, tmpDir) {
  const script = scriptOf(step);
  if (!script) return null;
  const out = path.join(tmpDir, script + '.json');

  // .mjs cannot be preloaded with -r (it is ESM). Those steps get NO entry,
  // which ci-scope reads as "always run" — correct, and honest about the limit.
  if (script.endsWith('.mjs')) return { script, deps: null, reason: 'esm' };

  const r = spawnSync(process.execPath, ['-r', PROBE, path.join('scripts', script)], {
    cwd: ROOT,
    env: { ...process.env, CI_DEPS_OUT: out, CI_DEPS_LABEL: script },
    stdio: 'ignore',
    timeout: 10 * 60 * 1000,
  });

  let deps = null;
  try { deps = JSON.parse(fs.readFileSync(out, 'utf8')).deps; } catch (_) {}
  // A test that FAILED may have exited before touching everything it normally
  // would, so its list is not trustworthy. No entry -> always run.
  if (r.status !== 0) return { script, deps: null, reason: `exit ${r.status}` };
  if (!Array.isArray(deps) || !deps.length) return { script, deps: null, reason: 'nothing recorded' };
  return { script, deps, reason: null };
}

function main() {
  if (!process.env.DATABASE_URL) {
    console.error('ci-deps-build: DATABASE_URL is required.');
    console.error('  Without a database every *-db.js suite self-skips and records almost nothing,');
    console.error('  which would produce a map that under-selects. Refusing to write one.');
    process.exit(1);
  }

  const steps = allSteps();
  const tmpDir = fs.mkdtempSync(path.join(os.tmpdir(), 'ci-deps-'));
  const map = {};
  const noEntry = [];
  let done = 0;

  for (const step of steps) {
    const r = runOne(step, tmpDir);
    done++;
    if (!r) continue;
    if (r.deps) map[r.script] = r.deps;
    else noEntry.push(`${r.script} (${r.reason})`);
    if (done % 100 === 0) console.log(`  …${done}/${steps.length}`);
  }

  // WRITTEN AS AN INDEX, NOT AS REPEATED PATHS. The obvious shape — every test
  // with its full list of path strings — came out at 5.3 MB, because the same
  // ~4,000 paths are repeated across 877 tests and a path costs ~38 bytes while
  // an index costs ~4. This repository's history is already 297 MB, and this
  // file is REGENERATED on a cadence, so every regeneration would add another
  // 5 MB to it for ever. Interning the paths once and referring to them by
  // number is the same information at a fraction of the weight.
  //
  // `ci-scope.loadDepMap` expands it back on read, so the selection logic — and
  // its tests — never see this representation.
  const files = [...new Set(Object.values(map).flat())].sort();
  const index = new Map(files.map((f, i) => [f, i]));

  fs.mkdirSync(OUT_DIR, { recursive: true });
  fs.writeFileSync(OUT_FILE, JSON.stringify({
    _what: 'Generated by scripts/ci-deps-build.js — DO NOT EDIT BY HAND. For each test, '
         + 'the repository files it actually read or required during a full run WITH a '
         + 'database, stored as indexes into `files`. A test that is absent from `tests` '
         + 'ALWAYS RUNS.',
    format: 'indexed-v1',
    builtAtUtcDay: new Date().toISOString().slice(0, 10),
    counts: {
      steps: steps.length,
      mapped: Object.keys(map).length,
      alwaysRun: noEntry.length,
      files: files.length,
    },
    alwaysRun: noEntry.sort(),
    files,
    tests: Object.fromEntries(
      Object.keys(map).sort().map((k) => [k, map[k].map((d) => index.get(d)).sort((a, b) => a - b)])
    ),
  }) + '\n');

  console.log(`ci-deps-build: ${Object.keys(map).length} tests mapped, `
    + `${noEntry.length} left as always-run`);
  console.log(`ci-deps-build: wrote ${path.relative(process.cwd(), OUT_FILE)}`);
  try { fs.rmSync(tmpDir, { recursive: true, force: true }); } catch (_) {}
}

if (require.main === module) main();

module.exports = { scriptOf, OUT_FILE };
