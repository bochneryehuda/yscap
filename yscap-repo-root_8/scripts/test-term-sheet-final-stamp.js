/**
 * PURE test — the INITIAL/FINAL term-sheet stamp rule
 * (src/lib/esign/term-sheet-stamp.js, owner-directed 2026-08-02).
 *
 *   node scripts/test-term-sheet-final-stamp.js
 *
 * THE BUG THIS PINS: the term sheet that goes out for signature through DocuSign
 * was printing "INITIAL TERM SHEET — NOT FINAL". The wording is drawn into the
 * PDF at generation time from ONE flag, and that flag was `esignSendGate(...)
 * .ready` — which includes the Product & pricing CONDITION SIGN-OFF, a step that
 * only happens AFTER the sheet is generated. So the flag was false every time
 * and every sheet on every file was stamped initial.
 *
 * The rule here ignores EXACTLY ONE requirement (that sign-off) and NOTHING
 * else, so the tests below are mostly about what must still block the stamp.
 */
const assert = require('assert');
const R = require('path').resolve(__dirname, '..');
const { stampFromDisposition, stampReason, IGNORED_AT_STAMP, REGENERATE_MESSAGE } =
  require(R + '/src/lib/esign/term-sheet-stamp');
const { gateDisposition } = require(R + '/src/lib/esign/gate-disposition');

let pass = 0;
const ok = (c, m) => { assert.ok(c, m); pass++; };

const B = (code, extra = {}) => ({ code, label: code, reason: `${code} outstanding`, ...extra });
const stamp = (outstanding, exception) => stampFromDisposition(gateDisposition(outstanding, exception));

// ---- the core rule --------------------------------------------------------
ok(stamp([]).final === true, 'nothing outstanding → FINAL');

ok(stamp([B('rtl_p1_product')]).final === true,
  'the P&P SIGN-OFF alone does NOT hold the stamp — it is the step that follows the registration this sheet is generated by, and requiring it made a FINAL stamp unreachable (the reported bug)');
ok(stamp([B('rtl_p1_product')]).blockers.length === 0,
  'and it is not reported as a blocker either');

// Everything else must still hold the stamp. These are the requirements that
// make the printed sheet CORRECT — a sheet calling itself final on numbers the
// appraisal never confirmed is worse than one that admits it is a draft.
for (const code of ['rtl_cond_appraisaldocs', 'rtl_p3_apprreview', 'expected_closing',
  'registration_stale', 'manual_approval', 'registration']) {
  const s = stamp([B(code)]);
  ok(s.final === false, `${code} outstanding → still INITIAL`);
  ok(s.blockers.length === 1 && s.blockers[0].code === code, `${code} is reported as the blocker`);
}

ok(IGNORED_AT_STAMP.size === 1 && IGNORED_AT_STAMP.has('rtl_p1_product'),
  'EXACTLY ONE requirement is ignored at stamp time — widening this set would let a sheet call itself final on an unfinished file');

// A mixed list: the ignored one drops out, the real one still blocks.
{
  const s = stamp([B('rtl_p1_product'), B('expected_closing')]);
  ok(s.final === false && s.blockers.length === 1 && s.blockers[0].code === 'expected_closing',
    'a real blocker alongside the ignored one still holds the stamp, and only the real one is named');
}

// ---- approved exceptions count exactly as they do for the send ------------
// A file the super-admin cleared to send must not then be stuck issuing an
// INITIAL sheet — the send guard would refuse the very package the exception
// was granted for.
{
  const outstanding = [B('rtl_p3_apprreview')];
  const legacyApproval = { status: 'approved' };           // pre-per-item: waives the ctc tier
  const d = gateDisposition(outstanding, legacyApproval);
  ok(d.sendAllowed === true, 'sanity: the legacy approval allows the send');
  ok(stampFromDisposition(d).final === true,
    'a waived blocker is not a blocker — an approved exception issues a FINAL sheet');
}
{
  // An explicit per-item waiver that does NOT cover everything: the send is
  // refused, and so is the final stamp.
  const outstanding = [B('rtl_p3_apprreview'), B('expected_closing')];
  const exc = {
    status: 'approved',
    waived_codes: ['rtl_p3_apprreview'],
    decided_gate: { outstanding: [{ code: 'rtl_p3_apprreview', reason: 'rtl_p3_apprreview outstanding' }] },
  };
  const d = gateDisposition(outstanding, exc);
  ok(d.sendAllowed === false, 'sanity: an incomplete waiver does not allow the send');
  ok(stampFromDisposition(d).final === false, 'and does not allow the FINAL stamp either');
}
{
  // A waiver whose blocker now fires for a DIFFERENT reason is not honored by
  // gateDisposition — the stamp must inherit that fail-closed behavior.
  const outstanding = [B('registration_stale', { reason: 'a REAL economics change' })];
  const exc = {
    status: 'approved',
    waived_codes: ['registration_stale'],
    decided_gate: { outstanding: [{ code: 'registration_stale', reason: 'a formatting echo' }] },
  };
  ok(stampFromDisposition(gateDisposition(outstanding, exc)).final === false,
    'a waiver that no longer means what was approved does not stamp a sheet final');
}
{
  const outstanding = [B('rtl_p3_apprreview')];
  for (const status of ['requested', 'denied', 'withdrawn', 'expired']) {
    ok(stampFromDisposition(gateDisposition(outstanding, { status })).final === false,
      `an exception that is ${status} (not approved) never stamps a sheet final`);
  }
}

// ---- fails closed on junk -------------------------------------------------
ok(stampFromDisposition(null).final === true && stampFromDisposition(null).blockers.length === 0,
  'a disposition with no outstanding list is "nothing outstanding" — the DB reader above is what refuses an UNREADABLE gate (it never reaches here)');
ok(stampFromDisposition({ outstanding: [null, undefined, B('expected_closing')] }).blockers.length === 1,
  'junk entries in the outstanding list are skipped, not counted or thrown on');

// ---- wording --------------------------------------------------------------
ok(/still outstanding/i.test(stampReason([B('expected_closing', { label: 'Estimated closing date' })])),
  'stampReason names what is outstanding');
ok(stampReason([]).length > 0, 'stampReason always says something, even with no blockers');
ok(typeof REGENERATE_MESSAGE === 'string', 'the stamp module still exports its wording constant');

// ============================================================================
// THE FIX (owner-directed 2026-08-06): the term sheet is now BUILT ON OUR SERVER
// at send time — pressing Send always produces the FINAL from the last
// registration, so the old "reuse the stored initial → refuse the send →
// re-register" loop (the owner's reported bug) is GONE. The stamp rule above is
// still exercised (staff.js reports termSheetFinal), but it no longer gates the
// send. These checks pin the new wiring.
// ============================================================================
{
  const src = require('fs').readFileSync(R + '/src/lib/esign/orchestrate.js', 'utf8');
  ok(/kind: 'term_sheet',[\s\S]{0,200}?generate: true/.test(src),
    'the term_sheet package doc is generate:true — BUILT fresh at send time, never reused from the stored P&P copy');
  ok(!/doc\.term_sheet_final !== true/.test(src),
    'the old "only initial → refuse the send" block is REMOVED (the sender generates the final now)');
  ok(!/TERM_SHEET_NOT_FINAL/.test(src),
    'the TERM_SHEET_NOT_FINAL refusal code is gone');
  ok(/function buildTermSheetView/.test(src) && /termsheet: buildTermSheetView/.test(src),
    'loadDocGenData assembles the term-sheet view from the registered quote (parity)');
  ok(/prefix: 'ts_b1'/.test(src) && /prefix: 'ts_b2'/.test(src) && /prefix: 'ts_lo'/.test(src) && /prefix: 'ts_admin'/.test(src),
    'the view emits all four signer prefixes (borrower/co/LO/admin) — matching buildRoster + tabsFor, so no recipient anchor is ever missing');
}
{
  const src = require('fs').readFileSync(R + '/src/lib/esign/docgen.js', 'utf8');
  ok(/term_sheet: buildTermSheet/.test(src),
    'docgen dispatches the term_sheet doc_kind to the server-side builder');
}
{
  const src = require('fs').readFileSync(R + '/src/lib/esign/tracking.js', 'utf8');
  ok(/block: false/.test(src) && !/REGENERATE_MESSAGE/.test(src),
    'the panel no longer hard-holds the term-sheet Send on a stored "initial" stamp — the send builds the final (real esignSendGate still governs the send)');
}
{
  const src = require('fs').readFileSync(R + '/app-v2/src/components/ProductStudioPanel.jsx', 'utf8');
  ok(/const stampFinal = false;/.test(src),
    "Products & Pricing produces ONLY the initial (owner's rule) — the FINAL is built by the sender");
}

// ---- the server builder produces a valid FINAL PDF carrying EXACTLY the
// DocuSign anchors the send engine seeds (orchestrate.tabsFor, prefix ts). ----
{
  const { buildTermSheet } = require(R + '/src/lib/esign/term-sheet-pdf');
  const data = {
    application: { loanNo: 'YSCAP1' },
    termsheet: {
      final: true, programName: 'Gold Standard Program', primaryName: 'MW Trading LLC',
      partiesSub: 'Vesting entity', purposeLine: 'Purchase', propertyLine: 'Property: 1 Main St, NY',
      validThrough: 'Valid through Jan 1, 2027', loanAmount: '$487,500', noteRate: '9.625%',
      termLine: '12-month term',
      structureRows: [{ k: 'Purchase price', v: '$400,000' }, { k: 'Total loan amount', v: '$487,500', opts: { bold: true, accent: true } }, { k: 'Omitted', v: '' }],
      termRows: [{ k: 'Loan term', v: '12 months' }],
      disclosures: [{ h: 'Business purpose only', body: 'Business purpose.' }],
      signers: [
        { name: 'A B', role: 'Borrower / guarantor', prefix: 'ts_b1' },
        { name: 'C D', role: 'Co-borrower / guarantor', prefix: 'ts_b2' },
        { name: 'Officer', role: 'Loan officer', prefix: 'ts_lo' },
        { name: 'YS Capital Group', role: 'Authorized signer', prefix: 'ts_admin' },
      ],
    },
  };
  const buf = buildTermSheet(data);
  ok(Buffer.isBuffer(buf) && buf.slice(0, 5).toString() === '%PDF-', 'buildTermSheet returns a real PDF');
  const s = buf.toString('latin1');
  for (const a of ['/ts_b1_sig/', '/ts_b1_dt/', '/ts_b2_sig/', '/ts_b2_dt/', '/ts_lo_sig/', '/ts_lo_dt/', '/ts_admin_sig/', '/ts_admin_dt/']) {
    ok(s.includes(a), `the FINAL term sheet carries the ${a} anchor for the send engine`);
  }
  ok(/FINAL TERM SHEET/.test(s), 'a final sheet prints the FINAL stamp');
  ok(!/INITIAL TERM SHEET/.test(s), 'a final sheet never prints "INITIAL TERM SHEET — NOT FINAL"');
  // A draft renders the initial stamp (used only for a preview/record copy).
  const draft = buildTermSheet({ application: {}, termsheet: { ...data.termsheet, final: false } });
  ok(/INITIAL TERM SHEET/.test(draft.toString('latin1')), 'final:false prints the INITIAL stamp');
}

console.log(`term-sheet final stamp: ${pass} checks passed`);
