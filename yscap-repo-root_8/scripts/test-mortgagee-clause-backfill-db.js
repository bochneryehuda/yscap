'use strict';
/**
 * db/650 HEALS THE MORTGAGEE-CLAUSE INSTRUCTIONS ALREADY SAVED ON FILES.
 *
 * `LENDER_MORTGAGEE_CLAUSE` spelled our street "MONROSE" until 2026-08-30, and underwriting writes
 * that constant into `document_findings.how_to` / `.file_value` at analysis time — the sentence a
 * person reads out when asking an insurance agent to RE-ISSUE a policy or a title company to CORRECT
 * Schedule A. Correcting the constant fixes every finding computed from now on and reaches none of
 * the ones already written; `underwriting/store.js` only replaces them when that document is
 * re-analyzed. db/650 is the other half (owner-directed 2026-08-30: *"fix the already-saved
 * findings too"*), and this suite is what proves it.
 *
 * THE CENTRAL ASSERTION IS SECTION B, AND IT IS DERIVED RATHER THAN RESTATED. A healed row is not
 * checked against a hand-typed "expected" sentence — it is compared BYTE FOR BYTE against what the
 * CURRENT production code generates for the same finding today. That is the real contract: after the
 * backfill, a row written months ago must be indistinguishable from one a fresh analysis would write.
 * Retyping the sentence here would prove only that this file agrees with itself.
 *
 * SECTION C IS THE ONE THAT MATTERS MOST FOR HONESTY. `doc_value` is what the BINDER ACTUALLY SAID,
 * read off the vendor's own document. One fixture is a binder genuinely printed with "5 New Monrose
 * Avenue" — because we dictated that spelling for weeks, such binders really exist — and the
 * migration must leave it exactly as it was. A backfill that "helpfully" corrected the evidence too
 * would erase the fact that the document and our expectation ever differed.
 *
 * MUTATION-PROVEN (CLAUDE.md build rule 2) — measured 2026-08-30 against a REAL PostgreSQL 16, never
 * a mock, with the whole migration chain applied to a fresh database first. Control 48 checks / 0
 * failures, confirmed before and after every mutation:
 *   • remove the document_findings UPDATE from db/650        → 22/48, 26 red
 *   • remove the finding_escalations UPDATE from db/650      → 44/48,  4 red (section D)
 *   • also rewrite doc_value, case-insensitively — the sloppy
 *     version somebody would plausibly write                 → 47/48,  1 red (section C, the
 *     evidence check: the mixed-case binder text is exactly what a `regexp_replace(... 'gi')`
 *     would corrupt and an exact-match `replace()` leaves alone)
 *   • heal the rows but record nothing in audit_log          → 45/48,  3 red (section E)
 *   • drop the WHERE guard so it rewrites every row, always  → 45/48,  3 red (section F idempotency,
 *     plus the stranger row that must never have been touched)
 *
 * Skips cleanly when DATABASE_URL is unset.
 */

if (!process.env.DATABASE_URL) { console.log('test-mortgagee-clause-backfill-db: SKIPPED (no DATABASE_URL)'); process.exit(0); }

const fs = require('fs');
const path = require('path');
const db = require('../src/db');
const { ensureSchema } = require('../src/migrate-boot');
const { computeInsuranceFindings } = require('../src/lib/underwriting/doc-checks');
const { computeTitleFindings } = require('../src/lib/underwriting/title-checks');

let n = 0, failed = 0;
const ok = (cond, label) => { n++; if (cond) return; failed++; console.error('  ✘ ' + label); };
const eq = (a, b, label) => ok(a === b, `${label}\n      got:      ${JSON.stringify(a)}\n      expected: ${JSON.stringify(b)}`);

const MIGRATION = path.join(__dirname, '..', 'db', '650_saved_mortgagee_instructions_say_montrose.sql');
const runMigration = async () => db.query(fs.readFileSync(MIGRATION, 'utf8'));

// The pre-fix street, and the inverse substitution that reconstructs exactly what the old code
// wrote. The two constants differ by this one token and nothing else, so applying it to today's
// output reproduces the historical row verbatim — a faithful fixture rather than a typed guess.
const NEW_ST = '5 NEW MONTROSE AVE';
const OLD_ST = '5 NEW MONROSE AVE';
const toOld = (s) => (s == null ? s : String(s).split(NEW_ST).join(OLD_ST));

// ---------------------------------------------------------------------------
// The five findings that carry the clause, generated by the REAL production code.
// ---------------------------------------------------------------------------
const insBase = { readable: true, dwellingCoverage: 500000, policyEffective: '2026-01-01', policyExpiration: '2027-01-01', mortgageeClausePresent: true };
const ins = (clause) => computeInsuranceFindings(Object.assign({}, insBase, { mortgageeClause: clause }), { borrower_name: 'Moses Weil' }, {});
const titleFile = { property_type: 'Single Family', property_address: { street: '1 Main St' } };
const titleBase = { readable: true, propertyAddress: { street: '1 Main St' }, vestedOwners: ['Michael Moran'] };
const title = (clause) => computeTitleFindings(Object.assign({}, titleBase, { mortgageeClause: clause }), titleFile, {});
const pick = (list, code) => (list || []).find((f) => f.code === code) || null;

// A binder genuinely printed with the misspelling — these exist because we dictated it.
const BINDER_WITH_MISSPELLING = 'YS Capital Group ISAOA/ATIMA, 5 New Monrose Avenue, Basement, Brooklyn, New York 11211';

const CASES = [
  { f: pick(ins('Wells Fargo Bank, N.A. ISAOA/ATIMA, 1 Home Campus, Des Moines, IA 50328'), 'insurance_wrong_mortgagee'), source: 'insurance', status: 'open' },
  { f: pick(ins('YS CAPITAL GROUP ISAOA/ATIMA'), 'insurance_mortgagee_address'), source: 'insurance', status: 'resolved' },
  { f: pick(ins('YS Capital Group ISAOA/ATIMA, 1 Executive Dr, Fort Lee, NJ 07024'), 'insurance_mortgagee_address_unrecognized'), source: 'insurance', status: 'superseded' },
  { f: pick(title('Wells Fargo Bank, N.A. ISAOA/ATIMA'), 'title_wrong_mortgagee'), source: 'title', status: 'open' },
  { f: pick(title('YS CAPITAL GROUP ISAOA/ATIMA'), 'title_mortgagee_address'), source: 'title', status: 'dismissed' },
];

(async () => {
  let borId = null, appId = null;
  try {
    await ensureSchema();

    // ---- fixtures: a file, and the five findings AS THEY WERE WRITTEN BEFORE THE FIX ----
    borId = (await db.query(`INSERT INTO borrowers (first_name, last_name) VALUES ('Moses','Weil') RETURNING id`)).rows[0].id;
    appId = (await db.query(`INSERT INTO applications (borrower_id) VALUES ($1) RETURNING id`, [borId])).rows[0].id;

    ok(CASES.every((c) => c.f), 'all five clause-carrying findings were generated by the production code');
    ok(CASES.every((c) => /MONROSE/.test(toOld(c.f.howTo)) && !/MONTROSE/.test(toOld(c.f.howTo))),
      'the reconstructed pre-fix sentences really do carry the misspelled street');

    const ids = [];
    for (const c of CASES) {
      const r = await db.query(
        `INSERT INTO document_findings (application_id, borrower_id, source, code, severity, field, doc_value, file_value, title, how_to, status)
         VALUES ($1,$2,$3,$4,$5,'mortgagee_clause',$6,$7,$8,$9,$10) RETURNING id`,
        [appId, borId, c.source, c.f.code, c.f.severity, c.f.docValue == null ? null : String(c.f.docValue),
         toOld(c.f.fileValue), c.f.title, toOld(c.f.howTo), c.status]);
      ids.push({ id: r.rows[0].id, c });
    }

    // The evidence row: a finding whose doc_value is a real binder carrying the misspelling, plus a
    // human-typed note that also carries it. Neither is ours to rewrite.
    const evidence = pick(ins(BINDER_WITH_MISSPELLING), 'insurance_mortgagee_address_unrecognized')
      || pick(ins('YS CAPITAL GROUP ISAOA/ATIMA'), 'insurance_mortgagee_address');
    const evId = (await db.query(
      `INSERT INTO document_findings (application_id, borrower_id, source, code, severity, doc_value, file_value, title, how_to, status, resolution_note)
       VALUES ($1,$2,'insurance',$3,'info',$4,$5,$6,$7,'open',$8) RETURNING id`,
      [appId, borId, evidence.code, BINDER_WITH_MISSPELLING, toOld(evidence.fileValue), evidence.title,
       toOld(evidence.howTo), 'Agent confirmed the binder prints Monrose — chasing a corrected copy.'])).rows[0].id;

    // A finding that has nothing to do with us: it must come out byte-identical.
    const strangerHowTo = 'The policy names 5 New Monrose Holdings LLC as an additional insured — confirm with the agent.';
    const strId = (await db.query(
      `INSERT INTO document_findings (application_id, borrower_id, source, code, severity, doc_value, file_value, title, how_to, status)
       VALUES ($1,$2,'insurance','insurance_named_insured_mismatch','warning',$3,$4,'Named insured',$5,'open') RETURNING id`,
      [appId, borId, 'Somebody Else LLC', '5 New Monrose Holdings LLC', strangerHowTo])).rows[0].id;

    // The escalation snapshot of the first finding — a separate copy that is never re-read.
    const escId = (await db.query(
      `INSERT INTO finding_escalations (application_id, finding_id, borrower_id, code, severity, field, title, how_to, doc_value, file_value, question)
       VALUES ($1,$2,$3,$4,$5,'mortgagee_clause',$6,$7,$8,$9,$10) RETURNING id`,
      [appId, ids[0].id, borId, CASES[0].f.code, CASES[0].f.severity, CASES[0].f.title,
       toOld(CASES[0].f.howTo), String(CASES[0].f.docValue), toOld(CASES[0].f.fileValue),
       'Agent says the Monrose address is what we sent them.'])).rows[0].id;

    const auditBefore = Number((await db.query(
      `SELECT count(*) c FROM audit_log WHERE action='mortgagee_clause_street_corrected' AND detail->>'applicationId'=$1`, [appId])).rows[0].c);

    // ---- A. the backfill runs ------------------------------------------------
    await runMigration();

    const rows = (await db.query(`SELECT * FROM document_findings WHERE application_id=$1`, [appId])).rows;
    const byId = new Map(rows.map((r) => [r.id, r]));

    // ---- B. every healed row equals what TODAY'S code writes, byte for byte ----
    for (const { id, c } of ids) {
      const r = byId.get(id);
      eq(r.how_to, c.f.howTo, `${c.f.code}: how_to is exactly what a fresh analysis writes today`);
      eq(r.file_value, c.f.fileValue, `${c.f.code}: file_value is exactly today's clause`);
      ok(!/MONROSE/i.test(r.how_to) || /MONTROSE/i.test(r.how_to), `${c.f.code}: no bare "Monrose" survives in how_to`);
      ok(/MONTROSE/i.test(r.how_to), `${c.f.code}: the instruction now says Montrose`);
      ok(r.status === c.status, `${c.f.code}: the row's status (${c.status}) was not disturbed`);
    }
    ok(ids.some(({ c }) => c.status !== 'open'), 'closed rows were part of this fixture, not just open ones');
    ok(ids.filter(({ id }) => /MONTROSE/i.test(byId.get(id).how_to)).length === 5,
      'all five statuses (open, resolved, superseded, dismissed) were corrected');

    // ---- C. THE EVIDENCE IS UNTOUCHED ----------------------------------------
    const ev = byId.get(evId);
    eq(ev.doc_value, BINDER_WITH_MISSPELLING,
      'doc_value — what the binder ACTUALLY said — is left exactly as it was read off the document');
    eq(ev.resolution_note, 'Agent confirmed the binder prints Monrose — chasing a corrected copy.',
      'a note a human typed is not rewritten by a migration');
    ok(/MONTROSE/i.test(ev.how_to), 'while the instruction on that same row IS corrected');

    const str = byId.get(strId);
    eq(str.how_to, strangerHowTo, 'an unrelated finding that merely contains the word is byte-identical');
    eq(str.file_value, '5 New Monrose Holdings LLC', 'and so is its file_value — the guard needs the WHOLE old address');

    // ---- D. the escalation snapshot is healed in its own right ----------------
    const esc = (await db.query(`SELECT * FROM finding_escalations WHERE id=$1`, [escId])).rows[0];
    eq(esc.how_to, CASES[0].f.howTo, 'the escalated copy of the sentence is corrected too');
    eq(esc.file_value, CASES[0].f.fileValue, 'and its file_value with it');
    eq(esc.doc_value, String(CASES[0].f.docValue), 'its doc_value evidence is untouched');
    eq(esc.question, 'Agent says the Monrose address is what we sent them.',
      'and the escalator\'s own words are untouched');

    // ---- E. nothing is lost: every correction is recorded ---------------------
    const audits = (await db.query(
      `SELECT * FROM audit_log WHERE action='mortgagee_clause_street_corrected' AND detail->>'applicationId'=$1 ORDER BY id`, [appId])).rows;
    eq(audits.length - auditBefore, 7, 'one audit row per corrected row (6 findings + 1 escalation)');
    ok(audits.every((a) => a.actor_kind === 'system'), 'recorded as a system action');
    ok(audits.some((a) => a.entity_type === 'document_finding'), 'findings are recorded');
    ok(audits.some((a) => a.entity_type === 'finding_escalation'), 'escalations are recorded');
    ok(audits.every((a) => a.detail.was === 'MONROSE' && a.detail.now === 'MONTROSE'), 'both spellings are on the record');
    ok(audits.every((a) => a.detail.migration === 'db/650'), 'and the migration that did it is named');
    ok(!audits.some((a) => a.entity_id === strId), 'the untouched stranger row produced no audit entry');

    // ---- F. idempotent: migrations replay on every boot -----------------------
    await runMigration();
    await runMigration();
    const auditsAfter = Number((await db.query(
      `SELECT count(*) c FROM audit_log WHERE action='mortgagee_clause_street_corrected' AND detail->>'applicationId'=$1`, [appId])).rows[0].c);
    eq(auditsAfter, audits.length, 'two more replays correct nothing and write no further audit rows');
    const replayed = (await db.query(`SELECT how_to, file_value FROM document_findings WHERE id=$1`, [ids[0].id])).rows[0];
    eq(replayed.how_to, CASES[0].f.howTo, 'and the text is stable across replays');
    eq(replayed.file_value, CASES[0].f.fileValue, 'file_value likewise');

    console.log(failed
      ? `test-mortgagee-clause-backfill-db: ${n - failed}/${n} passed, ${failed} FAILED`
      : `test-mortgagee-clause-backfill-db: ${n} checks passed`);
  } catch (e) {
    failed++;
    console.error('  ✘ threw:', e && e.message);
    console.error(e && e.stack);
  } finally {
    try {
      if (appId) {
        await db.query(`DELETE FROM audit_log WHERE action='mortgagee_clause_street_corrected' AND detail->>'applicationId'=$1`, [appId]);
        await db.query(`DELETE FROM applications WHERE id=$1`, [appId]);
      }
      if (borId) await db.query(`DELETE FROM borrowers WHERE id=$1`, [borId]);
    } catch (_) { /* cleanup is best-effort */ }
    await db.pool.end().catch(() => {});
    process.exit(failed ? 1 : 0);
  }
})();
