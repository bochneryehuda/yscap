/**
 * The document's identity line. The condition it answers comes first (that is
 * what a processor is looking for), then the kind of document, and only as a
 * LAST resort a generic phrase — and even that names how it arrived rather than
 * the old catch-all "General upload".
 *
 * `row.item_label` is the condition label the list query already joins in.
 */
function documentTitle(row) {
  const r = row || {};
  const item = trimmed(r.item_label);
  if (item) return item;
  const kind = trimmed(r.doc_kind);
  if (kind) return DOC_KINDS[kind] || humanize(kind);
  const src = sourceType(r);
  if (src && src.label !== 'Staff upload' && src.label !== 'Borrower upload') return src.label;
  if (r.track_record_id) return 'Track-record document';
  if (r.llc_id) return 'Vesting-entity document';
  // Truthful catch-all: it really is a loose file on the loan, and we say so.
  return 'Filed on the loan — not attached to a condition';
}

