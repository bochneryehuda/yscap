/* WHAT the reader was actually doing, from the URL they hit. A refusal is kept
   deliberately — "someone tried to open this and was turned away" is exactly
   the kind of thing an audit is looking for. */
function accessVerb(method, path, status) {
  const p = trimmed(path).toLowerCase();
  const denied = Number(status) === 403 || Number(status) === 401;
  let what = 'Opened the document';
  if (/\/download/.test(p)) what = /inline=1/.test(p) ? 'Previewed the document' : 'Downloaded the document';
  else if (/\/dossier/.test(p)) what = 'Looked at this history';
  else if (/\/ocr/.test(p)) what = 'Ran text recognition on it';
  else if (/\/review/.test(p)) what = 'Reviewed it';
  else if (trimmed(method).toUpperCase() === 'DELETE') what = 'Tried to delete it';
  return denied ? `${what} — REFUSED` : what;
}

/**
 * The access ledger. Built from the request log (which carries the IP and the
 * outcome of every attempt, including refusals) and topped up from the audit
 * log's own `download_document` rows so a document predating the request log
 * still shows its downloads.
 */
function buildAccess(requests, audits) {
  const out = [];
  for (const r of (Array.isArray(requests) ? requests : [])) {
    if (!r) continue;
    out.push({
      at: r.at || null,
      who: trimmed(r.actor_email) || (trimmed(r.actor_kind) ? humanize(r.actor_kind) : 'unknown'),
      role: trimmed(r.actor_role) || null,
      what: accessVerb(r.method, r.path, r.status),
      status: r.status == null ? null : Number(r.status),
      ip: r.ip || null,
      denied: Number(r.status) === 403 || Number(r.status) === 401,
      impersonator: trimmed(r.impersonator_name) || null,
    });
  }
  const seen = new Set(out.map((a) => `${a.at}`));
  for (const a of (Array.isArray(audits) ? audits : [])) {
    if (!a || trimmed(a.action) !== 'download_document') continue;
    if (seen.has(`${a.created_at}`)) continue;
    out.push({
      at: a.created_at || null,
      who: trimmed(a.actor_name) || (ACTOR_KIND[trimmed(a.actor_kind)] || 'unknown'),
      role: null, what: 'Downloaded the document', status: 200,
      ip: a.ip_address || null, denied: false,
      impersonator: trimmed(a.impersonator_name) || null,
    });
  }
  return out.sort((x, y) => new Date(y.at || 0) - new Date(x.at || 0)).slice(0, 100);
}

/**
 * buildDossier(input) → the object the portal renders.
 *
 * Nothing here fails on a missing side-table: an empty list is simply a shorter
 * dossier. That matters because half the inputs are env-gated features.
 */
function buildDossier(input) {
  const i = input || {};
  const doc = i.doc || {};
  const placement = describePlacement(doc);
  const purpose = describePurpose(doc);
  const timeline = buildTimeline(i);
  const rs = reviewStatus(doc);
  const mirror = mirrorStatus(doc);
  const auth = authenticity(doc);

  return {
    id: doc.id || null,
    title: documentTitle(doc),
    filename: trimmed(doc.filename) || null,
    identity: {
      filename: trimmed(doc.filename) || null,
      kind: trimmed(doc.doc_kind) ? (DOC_KINDS[trimmed(doc.doc_kind)] || humanize(doc.doc_kind)) : null,
      kindCode: trimmed(doc.doc_kind) || null,
      contentType: trimmed(doc.content_type) || null,
      size: bytesLabel(doc.size_bytes),
      sizeBytes: doc.size_bytes == null ? null : Number(doc.size_bytes),
      sha256: trimmed(doc.sha256) || null,
      pages: pageRangeLabel(doc.page_range),
      splitFromId: doc.source_document_id || null,
      uploadedAt: doc.created_at || null,
      uploadedBy: actorLabel(doc.uploaded_by_kind, doc.uploaded_by_name),
      uploadedByKind: trimmed(doc.uploaded_by_kind) || null,
      arrivedAs: sourceType(doc) ? sourceType(doc).label : null,
      visibility: visibility(doc) ? visibility(doc).label : null,
      isCurrent: doc.is_current !== false,
    },
    placement,
    purpose,
    review: {
      status: trimmed(doc.review_status) || 'pending',
      label: rs.label,
      tone: rs.tone,
      note: rs.note,
      reviewedAt: doc.reviewed_at || null,
      reviewedBy: trimmed(doc.reviewed_by_name) || null,
      rejectionReason: trimmed(doc.rejection_reason) || null,
    },
    storage: {
      provider: trimmed(doc.storage_provider) || null,
      mirror,
      webUrl: trimmed(doc.sharepoint_web_url) || null,
      syncedAt: doc.sharepoint_backed_up_at || null,
      verifiedAt: doc.sharepoint_verified_at || null,
      integrity: integrityLabel(doc.sharepoint_integrity),
      attempts: doc.sharepoint_backup_attempts == null ? null : Number(doc.sharepoint_backup_attempts),
      error: trimmed(doc.sharepoint_backup_error) || null,
      deadReason: trimmed(doc.sharepoint_dead_reason) || null,
      skippedReason: trimmed(doc.sharepoint_skipped_reason) || null,
      nextAttemptAt: doc.sharepoint_next_attempt_at || null,
    },
    authenticity: auth,
    // What this document IS elsewhere in the system — the credit report, the
    // appraisal, an executed signature package, the flood certificate…
    roles: (Array.isArray(i.roles) ? i.roles : []).filter(Boolean),
    // THE ACCESS LEDGER — who opened, previewed or downloaded it, when, and
    // from where. A regulated file has to be able to answer this, and it is
    // deliberately NOT folded into the timeline: a busy document produces
    // hundreds of views and would drown its own story.
    access: buildAccess(i.access, i.audits),
    versions: Array.isArray(i.versions) ? i.versions : [],
    timeline,
    counts: {
      events: timeline.length,
      findings: (Array.isArray(i.findings) ? i.findings : []).length,
      openFindings: (Array.isArray(i.findings) ? i.findings : [])
        .filter((f) => f && trimmed(f.status) === 'open').length,
      versions: (Array.isArray(i.versions) ? i.versions : []).length,
    },
  };
}

