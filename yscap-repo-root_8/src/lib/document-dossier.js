/**
 * describePurpose(row) → { headline, why[], asked }
 *
 * The headline answers "what is this document FOR". `why` collects the
 * supporting sentences: the condition's own hint (the words the borrower was
 * shown), the reason the condition exists at all (its origin), and what
 * accepting it unblocks.
 */
function describePurpose(row) {
  const r = row || {};
  const p = describePlacement(r);
  const cond = p.condition;
  const why = [];

  let headline;
  if (cond && cond.label) {
    headline = cond.isGate
      ? `Evidence for the gate “${cond.label}” — the file cannot move on until this is satisfied.`
      : `Evidence for the condition “${cond.label}”.`;
  } else {
    const kind = trimmed(r.doc_kind);
    const src = sourceType(r);
    headline = kind && (DOC_KINDS[kind] || humanize(kind))
      ? `${DOC_KINDS[kind] || humanize(kind)} on this file.`
      : src ? src.why
      : 'Filed on this loan for the record.';
  }

  // The exact words the borrower (or the processor) was shown when asked.
  const asked = trimmed(cond && (cond.borrowerHint || cond.hint)) || null;
  if (asked) why.push(`What was asked for: ${asked}`);

  const src = sourceType(r);
  if (src) why.push(src.why);

  if (cond && cond.originKind) {
    const originWords = {
      auto: 'PILOT’s condition rules put this condition on the file automatically.',
      rule: 'PILOT’s condition rules put this condition on the file automatically.',
      manual: 'A member of the loan team added this condition by hand.',
      template: 'This condition comes from the standard condition library for this program.',
      note_buyer: 'The capital provider requires this condition.',
      investor: 'The capital provider requires this condition.',
      exception: 'This condition came out of a policy exception on the file.',
    };
    const w = originWords[cond.originKind] || `Condition origin: ${humanize(cond.originKind)}.`;
    why.push(cond.originDetail ? `${w} (${cond.originDetail})` : w);
  }

  if (cond && cond.isRequired) why.push('The condition is REQUIRED — it cannot simply be waived away.');

  if (r.track_record_id) why.push('It also backs a project on the borrower’s track record, which their experience count is built from.');
  if (r.llc_id) why.push('Rejecting it un-verifies the vesting entity, because the verification stood on this document.');

  return { headline, why, asked };
}

// ---------------------------------------------------------------------------
// 3. WHAT HAPPENED — the merged timeline.
// ---------------------------------------------------------------------------

const ev = (at, code, title, opts) => ({
  at: at || null,
  code,
  title,
  icon: (opts && opts.icon) || '•',
  tone: (opts && opts.tone) || 'info',
  detail: (opts && opts.detail) || null,
  actor: (opts && opts.actor) || null,
  // The real human behind a borrower-view session, when there was one.
  impersonator: (opts && opts.impersonator) || null,
  source: (opts && opts.source) || 'document',
});

function actorLabel(kind, name) {
  const n = trimmed(name);
  if (n) return n;
  return ACTOR_KIND[trimmed(kind)] || (trimmed(kind) ? humanize(kind) : null);
}

/**
 * buildTimeline(input) → [event] in CHRONOLOGICAL order (oldest first — a
 * document's history reads as a story, not as a news feed).
 *
 * Every input list is optional. The builder is deliberately forgiving: a caller
 * that cannot read one of the side tables (the AI tables are env-gated, the
 * pipeline tables ship behind a flag) simply passes nothing and the timeline is
 * shorter — never broken.
 *
 * DE-DUPLICATION: the document row and the audit log record the SAME accept /
 * reject event. The audit row is richer (it names the actor), so when an audit
 * row for a verdict exists we do not also derive one from `reviewed_at`.
 */
function buildTimeline(input) {
  const i = input || {};
  const doc = i.doc || {};
  const audits = Array.isArray(i.audits) ? i.audits : [];
  const versions = Array.isArray(i.versions) ? i.versions : [];
  const extractions = Array.isArray(i.extractions) ? i.extractions : [];
  const findings = Array.isArray(i.findings) ? i.findings : [];
  const jobs = Array.isArray(i.jobs) ? i.jobs : [];
  const syncRows = Array.isArray(i.syncRows) ? i.syncRows : [];
  const lifecycle = Array.isArray(i.lifecycle) ? i.lifecycle : [];

  const out = [];

  // ---- 1. It arrived ------------------------------------------------------
  const uploadedByAudit = audits.some((a) => /^upload/.test(trimmed(a && a.action)));
  if (!uploadedByAudit) {
    const who = actorLabel(doc.uploaded_by_kind, doc.uploaded_by_name);
    const bits = [bytesLabel(doc.size_bytes), trimmed(doc.content_type) || null].filter(Boolean);
    out.push(ev(doc.created_at, 'uploaded', 'Uploaded', {
      icon: '⬆️', tone: 'info',
      actor: who,
      detail: [trimmed(doc.filename), bits.join(' · ')].filter(Boolean).join(' — ') || null,
    }));
  }

  // ---- 2. Everything a human did to it (audit log) -----------------------
  for (const a of audits) {
    const action = trimmed(a && a.action);
    if (!action) continue;
    const meta = DOC_AUDIT[action] || { title: humanize(action), icon: '•', tone: 'info' };
    const d = (a && a.detail) || {};
    const bits = [];
    if (d.reason) bits.push(`Reason: ${d.reason}`);
    if (d.note) bits.push(`Note to the borrower: ${d.note}`);
    if (d.engine) bits.push(`Engine: ${d.engine}`);
    if (d.pageCount) bits.push(`${d.pageCount} page${Number(d.pageCount) === 1 ? '' : 's'}`);
    if (d.filename && action !== 'upload_document') bits.push(String(d.filename));
    if (d.wasMirrored) bits.push('It had already been mirrored to SharePoint.');
    // ON-BEHALF-OF. An action taken inside a borrower-view session is recorded
    // under the BORROWER's identity — which is correct, that is who the session
    // ran as — so naming only the actor tells the reader a borrower did
    // something a staff member did. Name the real human, and mark the row, so
    // it can never be read as the borrower's own act.
    const onBehalf = trimmed(a.impersonator_name);
    if (onBehalf) bits.unshift(`⚠️ Done by ${onBehalf} while signed in as this borrower.`);
    out.push(ev(a.created_at, action, meta.title, {
      icon: meta.icon, tone: onBehalf ? 'warn' : meta.tone, source: 'audit',
      actor: actorLabel(a.actor_kind, a.actor_name),
      impersonator: onBehalf || null,
      detail: bits.join(' · ') || null,
    }));
  }

  // ---- 3. The verdict, when no audit row carries it ----------------------
  const verdictInAudit = audits.some((a) => /^(accept_document|reject_document)/.test(trimmed(a && a.action)));
  const rs = trimmed(doc.review_status);
  if (!verdictInAudit && doc.reviewed_at && (rs === 'accepted' || rs === 'rejected')) {
    out.push(ev(doc.reviewed_at, rs === 'accepted' ? 'accept_document' : 'reject_document',
      rs === 'accepted' ? 'Accepted' : 'Rejected', {
        icon: rs === 'accepted' ? '✅' : '⛔',
        tone: rs === 'accepted' ? 'ok' : 'bad',
        actor: trimmed(doc.reviewed_by_name) || null,
        detail: rs === 'rejected' && trimmed(doc.rejection_reason) ? `Reason: ${doc.rejection_reason}` : null,
      }));
  }

  // ---- 4. Version chain ---------------------------------------------------
  for (const v of versions) {
    if (!v) continue;
    if (trimmed(v.relation) === 'replaced_by') {
      out.push(ev(v.created_at, 'superseded', 'Replaced by a newer version', {
        icon: '🔁', tone: 'muted',
        detail: trimmed(v.filename) ? `Replaced by “${v.filename}”.` : null,
      }));
    } else if (trimmed(v.relation) === 'replaces') {
      out.push(ev(doc.created_at, 'replaces', 'Filed as a replacement', {
        icon: '🔁', tone: 'info',
        detail: trimmed(v.filename) ? `It replaced the earlier “${v.filename}”.` : null,
      }));
    }
  }
  // A superseded document with no visible successor still says so.
  if (rs === 'superseded' && !versions.some((v) => v && trimmed(v.relation) === 'replaced_by')) {
    out.push(ev(doc.reviewed_at || doc.created_at, 'superseded', 'Replaced by a newer version',
      { icon: '🔁', tone: 'muted' }));
  }

  // ---- 5. PILOT read it ---------------------------------------------------
  for (const x of extractions) {
    if (!x) continue;
    const type = trimmed(x.doc_type);
    const bits = [];
    if (x.confidence) bits.push(`Confidence: ${x.confidence}`);
    if (x.page_count) bits.push(`${x.page_count} page${Number(x.page_count) === 1 ? '' : 's'}`);
    if (x.ocr_engine) bits.push(`OCR: ${x.ocr_engine}`);
    if (x.ai_model) bits.push(`Model: ${x.ai_model}`);
    if (trimmed(x.status) === 'error' && x.reason) bits.push(`Why it failed: ${x.reason}`);
    const failed = trimmed(x.status) === 'error';
    out.push(ev(x.created_at, failed ? 'read_failed' : 'read', failed
      ? 'PILOT could not read the document'
      : `PILOT read the document${type ? ` as ${humanize(type).toLowerCase()}` : ''}`, {
      icon: failed ? '⚠️' : '🤖',
      tone: failed ? 'warn' : 'info',
      actor: 'PILOT',
      detail: bits.join(' · ') || null,
      source: 'ai',
    }));
  }

  // ---- 6. What that read raised ------------------------------------------
  for (const f of findings) {
    if (!f) continue;
    const sev = trimmed(f.severity) || 'info';
    out.push(ev(f.created_at, 'finding', `PILOT raised a ${sev} finding`, {
      icon: sev === 'fatal' ? '🚨' : sev === 'warning' ? '⚠️' : 'ℹ️',
      tone: sev === 'fatal' ? 'bad' : sev === 'warning' ? 'warn' : 'info',
      actor: 'PILOT',
      detail: [trimmed(f.title) || humanize(f.code),
        f.doc_value != null && f.file_value != null ? `Document says “${f.doc_value}”, the file says “${f.file_value}”.` : null,
      ].filter(Boolean).join(' — ') || null,
      source: 'ai',
    }));
    if (f.resolved_at) {
      out.push(ev(f.resolved_at, 'finding_resolved', `Finding ${trimmed(f.status) || 'resolved'}`, {
        icon: '☑️', tone: 'ok',
        actor: trimmed(f.resolved_by_name) || null,
        detail: [trimmed(f.title) || humanize(f.code), trimmed(f.resolution_note) || null].filter(Boolean).join(' — ') || null,
        source: 'ai',
      }));
    }
  }

  // ---- 7. The processing pipeline ----------------------------------------
  for (const j of jobs) {
    if (!j) continue;
    out.push(ev(j.created_at, 'job_queued', 'Queued for processing', {
      icon: '⏳', tone: 'muted', actor: 'PILOT', source: 'pipeline',
      detail: trimmed(j.document_family) ? `Routed as ${humanize(j.document_family).toLowerCase()}.` : null,
    }));
    const st = trimmed(j.status);
    if (['completed', 'failed_terminal', 'failed_retryable', 'cancelled', 'manual_review'].includes(st)) {
      const done = st === 'completed';
      out.push(ev(j.updated_at || j.created_at, `job_${st}`,
        done ? 'Processing finished'
          : st === 'manual_review' ? 'Sent for manual review'
          : st === 'cancelled' ? 'Processing cancelled'
          : 'Processing failed', {
          icon: done ? '✅' : st === 'manual_review' ? '👀' : '⚠️',
          tone: done ? 'ok' : st === 'manual_review' ? 'warn' : 'bad',
          actor: 'PILOT', source: 'pipeline',
          detail: [trimmed(j.last_error) || null,
            j.attempts ? `Attempt ${j.attempts}` : null].filter(Boolean).join(' · ') || null,
        }));
    }
  }

  // ---- 8. SharePoint ------------------------------------------------------
  if (doc.sharepoint_backed_up_at) {
    out.push(ev(doc.sharepoint_backed_up_at, 'sp_synced', 'Synced to SharePoint', {
      icon: '☁️', tone: 'ok', actor: 'PILOT', source: 'sharepoint',
      detail: doc.sharepoint_version ? `Version ${doc.sharepoint_version} in SharePoint.` : null,
    }));
  }
  if (doc.sharepoint_stamped_at) {
    out.push(ev(doc.sharepoint_stamped_at, 'sp_stamped', 'Filed under the loan’s SharePoint folder', {
      icon: '🏷', tone: 'muted', actor: 'PILOT', source: 'sharepoint',
    }));
  }
  if (doc.sharepoint_verified_at) {
    const integ = integrityLabel(doc.sharepoint_integrity);
    out.push(ev(doc.sharepoint_verified_at, 'sp_verified', 'SharePoint copy checked', {
      icon: integ && integ.tone === 'ok' ? '🛡' : '⚠️',
      tone: (integ && integ.tone) || 'muted',
      actor: 'PILOT', source: 'sharepoint',
      detail: integ ? integ.label : null,
    }));
  }
  if (doc.sharepoint_backup_error && doc.sharepoint_backup_attempted_at) {
    out.push(ev(doc.sharepoint_backup_attempted_at, 'sp_failed', 'SharePoint sync failed', {
      icon: '⚠️', tone: 'warn', actor: 'PILOT', source: 'sharepoint',
      detail: [trimmed(doc.sharepoint_backup_error),
        doc.sharepoint_backup_attempts ? `${doc.sharepoint_backup_attempts} attempt${Number(doc.sharepoint_backup_attempts) === 1 ? '' : 's'}` : null,
      ].filter(Boolean).join(' · ') || null,
    }));
  }
  if (doc.sharepoint_dead_reason) {
    out.push(ev(doc.sharepoint_next_attempt_at || doc.sharepoint_backup_attempted_at, 'sp_dead',
      'SharePoint sync gave up', {
        icon: '🛑', tone: 'bad', actor: 'PILOT', source: 'sharepoint',
        detail: trimmed(doc.sharepoint_dead_reason) || null,
      }));
  }
  if (doc.sharepoint_skipped_reason) {
    out.push(ev(doc.sharepoint_backup_attempted_at || doc.created_at, 'sp_skipped',
      'Deliberately not mirrored to SharePoint', {
        icon: '⊘', tone: 'muted', actor: 'PILOT', source: 'sharepoint',
        detail: trimmed(doc.sharepoint_skipped_reason) || null,
      }));
  }

  // ---- 9. Pushed OUT to an integration -----------------------------------
  // A DOCUMENT's outbound push is recorded per-integration (`sitewire_document_links`
  // today), NOT on the generic `sync_queue` — nothing ever enqueues a document
  // there, so reading that queue here would be permanently, silently empty.
  for (const s of syncRows) {
    if (!s) continue;
    const st = trimmed(s.status);
    const done = st === 'pushed' || st === 'verified' || st === 'done';
    const failed = st === 'failed' || st === 'error';
    const what = trimmed(s.which) ? ` (${humanize(s.which).toLowerCase()})` : '';
    out.push(ev(s.at || s.updated_at || s.created_at, `push_${st || 'queued'}`,
      done ? `Sent to the draw system${what}`
        : failed ? `Sending to the draw system failed${what}`
        : `Queued to send to the draw system${what}`, {
        icon: done ? '🔗' : failed ? '⚠️' : '⏳',
        tone: done ? 'ok' : failed ? 'bad' : 'muted',
        actor: trimmed(s.pushed_by_name) || 'PILOT', source: 'sync',
        detail: [trimmed(s.sitewire_document_name) || null, trimmed(s.last_error) || null]
          .filter(Boolean).join(' · ') || null,
      }));
  }

  // ---- 9b. DID IT ANSWER THE CONDITION IT WAS UPLOADED TO? ---------------
  // The most on-point record there is for "what was the purpose of this
  // document" — PILOT's per-requirement read of whether it actually cures.
  const PROOF = {
    satisfied: { title: 'PILOT read it as answering the condition', icon: '☑️', tone: 'ok' },
    partially_satisfied: { title: 'PILOT read it as only PARTLY answering the condition', icon: '◐', tone: 'warn' },
    not_satisfied: { title: 'PILOT read it as NOT answering the condition', icon: '⛔', tone: 'bad' },
    creates_new_finding: { title: 'It answers the condition but raised a new issue', icon: '⚠️', tone: 'warn' },
    unable_to_determine: { title: 'PILOT could not tell whether it answers the condition', icon: '❔', tone: 'muted' },
  };
  for (const p of (Array.isArray(i.proofs) ? i.proofs : [])) {
    if (!p) continue;
    const meta = PROOF[trimmed(p.result)]
      || { title: `Checked against the condition — ${humanize(p.result)}`, icon: '❔', tone: 'muted' };
    const reqs = Array.isArray(p.requirements_json) ? p.requirements_json : [];
    const missing = reqs.filter((r) => r && trimmed(r.status) && trimmed(r.status) !== 'satisfied')
      .map((r) => trimmed(r.label)).filter(Boolean);
    out.push(ev(p.created_at, 'clearance_proof', meta.title, {
      icon: meta.icon, tone: meta.tone, actor: 'PILOT', source: 'ai',
      detail: [trimmed(p.reviewer_summary) || null,
        missing.length ? `Still missing: ${missing.join(', ')}` : null,
        trimmed(p.recommended_action) ? `Suggested next step: ${humanize(p.recommended_action).toLowerCase()}` : null,
      ].filter(Boolean).join('\n') || null,
    }));
  }

  // ---- 9c. What PILOT proposed off the back of it ------------------------
  for (const s of (Array.isArray(i.suggestions) ? i.suggestions : [])) {
    if (!s) continue;
    const sev = trimmed(s.severity);
    out.push(ev(s.created_at, 'suggestion', 'PILOT suggested something from this document', {
      icon: '💡', tone: sev === 'fatal' ? 'bad' : sev === 'warning' ? 'warn' : 'info',
      actor: 'PILOT', source: 'ai',
      detail: [trimmed(s.title) || null, trimmed(s.body) ? String(s.body).slice(0, 300) : null]
        .filter(Boolean).join(' — ') || null,
    }));
    if (s.decided_at) {
      out.push(ev(s.decided_at, 'suggestion_decided',
        `A human ${humanize(s.status).toLowerCase()} PILOT's suggestion`, {
          icon: '👤', tone: 'ok', actor: trimmed(s.decided_by_name) || null, source: 'ai',
          detail: [trimmed(s.title) || null, trimmed(s.status_reason) || null].filter(Boolean).join(' — ') || null,
        }));
    }
  }

  // ---- 9d. HOW it was read — which engine, why, and what it cost ---------
  for (const r of (Array.isArray(i.routes) ? i.routes : [])) {
    if (!r) continue;
    const failed = trimmed(r.outcome) === 'failed';
    const bits = [
      trimmed(r.reason) || null,
      r.confidence == null ? null : `confidence ${Number(r.confidence).toFixed(2)}`,
      trimmed(r.challenger_provider) ? `double-checked against ${r.challenger_provider}` : null,
      r.latency_ms ? `${r.latency_ms}ms` : null,
      r.cost_cents ? `$${(Number(r.cost_cents) / 100).toFixed(2)}` : null,
    ].filter(Boolean);
    out.push(ev(r.created_at, failed ? 'route_failed' : 'route',
      failed ? `The reader failed on this document (${trimmed(r.provider) || 'unknown engine'})`
        : `Routed to ${trimmed(r.provider) || 'a reader'}${trimmed(r.service) ? ` · ${r.service}` : ''} to be read`, {
        icon: failed ? '⚠️' : '🧭', tone: failed ? 'warn' : 'muted',
        actor: 'PILOT', source: 'ai', detail: bits.join(' · ') || null,
      }));
  }

  // ---- 10. Packet lifecycle (split / merge / reclassify) -----------------
  for (const l of lifecycle) {
    if (!l) continue;
    const t = trimmed(l.event_type);
    if (!t) continue;
    out.push(ev(l.created_at, `lifecycle_${t}`, humanize(t), {
      icon: '📄', tone: 'info', source: 'lifecycle',
      actor: actorLabel(l.actor_kind, l.actor_name),
      detail: l.detail && typeof l.detail === 'object' && l.detail.note ? String(l.detail.note) : null,
    }));
  }

  // ---- 11. Authenticity ---------------------------------------------------
  if (doc.authenticity_checked_at) {
    const a = authenticity(doc);
    out.push(ev(doc.authenticity_checked_at, 'authenticity', 'Authenticity checked', {
      icon: a && a.tone === 'bad' ? '🚨' : '🔍',
      tone: (a && a.tone) || 'muted',
      actor: 'PILOT', source: 'ai',
      detail: a ? [a.label, a.score == null ? null : `score ${a.score}`].filter(Boolean).join(' · ') : null,
    }));
  }

  // Chronological. Rows with no timestamp sink to the bottom rather than
  // pretending to be the oldest thing that ever happened.
  const ts = (e) => {
    const v = e && e.at ? Date.parse(e.at) : NaN;
    return isFinite(v) ? v : Infinity;
  };
  return out.sort((a, b) => ts(a) - ts(b));
}

