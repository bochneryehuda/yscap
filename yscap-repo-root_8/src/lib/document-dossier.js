/**
 * DOCUMENT DOSSIER — the full story of ONE uploaded document.
 *
 * Owner-directed (2026-08-02): "Documents and exports … it's too vague, it just
 * says everywhere 'General upload'. We need to be more in detail what was
 * uploaded, to which condition was it uploaded, and what happened with that
 * document — was it accepted… all the details that is happening with this
 * document."
 *
 * The Documents & exports panel used to show a filename, a size, a date and a
 * one-word status. Everything else the system already knew about a document —
 * which condition it answered, which slot inside that condition, why that
 * condition exists, who reviewed it and when, what they said when they rejected
 * it, which version replaced it, whether it reached SharePoint, whether PILOT
 * could read it and what it found — was scattered across a dozen tables and
 * visible on no screen.
 *
 * This module is the PURE half: it owns the WORDING and the SHAPING. It never
 * touches the database, never throws on a missing field, and never invents a
 * fact — an unknown value renders as the honest "—"/null rather than a guess.
 * The route (src/routes/staff.js `GET /documents/:id/dossier`) does the reading
 * and hands the rows here; the portal renders what comes back.
 *
 * THE THREE QUESTIONS the panel must answer for every document:
 *   1. WHERE did it land?      → describePlacement()
 *   2. WHY was it uploaded?    → describePurpose()
 *   3. WHAT happened to it?    → buildTimeline()
 */

