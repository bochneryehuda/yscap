/**
 * describePlacement(row) → { where, whereLabel, lines[], condition, unattached }
 *
 * `row` is the document joined with its condition (`cond_*` fields), entity
 * (`llc_name`) and track record (`track_record_label`). Everything is optional.
 *
 * `where` is the machine code: condition | entity | track_record | lead |
 * chat | file. `lines` are the human sentences the panel prints.
 */
function describePlacement(row) {
  const r = row || {};
  const lines = [];
  let where = 'file';
  let whereLabel = 'Filed on the loan';

  const condLabel = trimmed(r.cond_label) || trimmed(r.item_label);
  if (r.checklist_item_id && condLabel) {
    where = 'condition';
    whereLabel = `Condition — ${condLabel}`;
    lines.push(`Uploaded to the condition “${condLabel}”.`);
  } else if (r.track_record_id) {
    where = 'track_record';
    const t = trimmed(r.track_record_label);
    whereLabel = t ? `Track record — ${t}` : 'Track record';
    lines.push(t ? `Filed on the borrower’s track-record project “${t}”.`
                 : 'Filed on the borrower’s track record.');
  } else if (r.llc_id) {
    where = 'entity';
    const n = trimmed(r.llc_name);
    whereLabel = n ? `Vesting entity — ${n}` : 'Vesting entity';
    lines.push(n ? `Filed on the vesting entity “${n}” — it travels with the entity to every file it vests into.`
                 : 'Filed on the vesting entity — it travels with the entity to every file it vests into.');
  } else if (r.lead_id) {
    where = 'lead';
    whereLabel = 'Lead record';
    lines.push('Filed on the lead record, before there was a loan file.');
  } else if (trimmed(r.source_type) === 'chat_attachment') {
    where = 'chat';
    whereLabel = 'Conversation attachment';
    lines.push('Sent as an attachment in a conversation — not part of the review queue.');
  } else {
    lines.push('Filed on the loan itself — it is not attached to any condition, so nothing is waiting on it.');
  }

  const slot = trimmed(r.slot_label);
  if (slot) lines.push(`It fills the “${slot}” slot inside that item.`);

  const pages = pageRangeLabel(r.page_range);
  if (pages && r.source_document_id) lines.push(`Split out of a larger upload — ${pages} of the original packet.`);
  else if (pages) lines.push(`Covers ${pages} of the upload.`);

  const vis = visibility(r);
  if (vis) lines.push(vis.note);

  const condition = r.checklist_item_id ? {
    id: r.checklist_item_id,
    label: condLabel || null,
    status: trimmed(r.cond_status) || null,
    audience: trimmed(r.cond_audience) || null,
    phase: trimmed(r.cond_phase) || null,
    category: trimmed(r.cond_category) || null,
    itemKind: trimmed(r.cond_item_kind) || null,
    isGate: !!r.cond_is_gate,
    isRequired: !!r.cond_is_required,
    hint: trimmed(r.cond_hint) || null,
    borrowerHint: trimmed(r.cond_borrower_hint) || null,
    originKind: trimmed(r.cond_origin_kind) || null,
    originDetail: trimmed(r.cond_origin_detail) || null,
    signedOffAt: r.cond_signed_off_at || null,
    signedOffBy: trimmed(r.cond_signed_off_by_name) || null,
    waivedAt: r.cond_waived_at || null,
  } : null;

  return { where, whereLabel, lines, condition, unattached: where === 'file' };
}

