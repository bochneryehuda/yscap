const str = (v) => (v == null ? '' : String(v));
const trimmed = (v) => str(v).trim();

/** `some_new_thing` → `Some new thing`. Used wherever a code has no wording. */
function humanize(code) {
  const s = trimmed(code).replace(/[_-]+/g, ' ').trim();
  if (!s) return '';
  return s.charAt(0).toUpperCase() + s.slice(1);
}

function bytesLabel(n) {
  const b = Number(n);
  if (!isFinite(b) || b <= 0) return null;
  if (b < 1024) return `${b} B`;
  if (b < 1024 * 1024) return `${Math.round(b / 1024)} KB`;
  return `${(b / (1024 * 1024)).toFixed(1)} MB`;
}

/** A page range stored as an int[] pair — `[3, 9]` → "pages 3–9". */
function pageRangeLabel(range) {
  if (!Array.isArray(range) || !range.length) return null;
  const a = Number(range[0]);
  const b = Number(range.length > 1 ? range[1] : range[0]);
  if (!isFinite(a) || !isFinite(b)) return null;
  return a === b ? `page ${a}` : `pages ${a}–${b}`;
}

function sourceType(row) { return SOURCE_TYPES[trimmed(row && row.source_type)] || null; }
function visibility(row) { return VISIBILITY[trimmed(row && row.visibility)] || null; }
function reviewStatus(row) {
  return REVIEW_STATUS[trimmed(row && row.review_status) || 'pending'] || REVIEW_STATUS.pending;
}
function mirrorStatus(row) {
  const raw = trimmed(row && row.sharepoint_mirror_status).toUpperCase();
  if (MIRROR_STATUS[raw]) return { code: raw, ...MIRROR_STATUS[raw] };
  // No FSM row yet: fall back to the columns that encode it implicitly.
  if (row && row.sharepoint_backed_up_at) return { code: 'DONE', ...MIRROR_STATUS.DONE };
  if (row && row.sharepoint_skipped_reason) return { code: 'SKIPPED', ...MIRROR_STATUS.SKIPPED };
  if (row && Number(row.sharepoint_backup_attempts) > 0) return { code: 'FAILED', ...MIRROR_STATUS.FAILED };
  return { code: 'PENDING', ...MIRROR_STATUS.PENDING };
}
function authenticity(row) {
  const lvl = trimmed(row && row.authenticity_level).toLowerCase();
  if (!lvl) return null;
  const meta = AUTHENTICITY[lvl] || { label: humanize(lvl), tone: 'muted' };
  return { level: lvl, ...meta, score: row.authenticity_score == null ? null : Number(row.authenticity_score) };
}

/** SharePoint integrity is free-text with a stable prefix (`ok`, `mismatch…`). */
function integrityLabel(value) {
  const v = trimmed(value);
  if (!v) return null;
  if (/^ok\b/.test(v)) return { label: 'Verified byte-for-byte', tone: 'ok', raw: v };
  if (/^mismatch/.test(v)) return { label: 'Copy does not match the original', tone: 'bad', raw: v };
  if (/^source-suspect/.test(v)) return { label: 'Source file looks damaged', tone: 'bad', raw: v };
  if (/^malware/.test(v)) return { label: 'Flagged by malware scanning', tone: 'bad', raw: v };
  if (v === 'item-missing') return { label: 'Missing in SharePoint', tone: 'bad', raw: v };
  if (v === 'local-missing') return { label: 'Missing in PILOT’s storage', tone: 'bad', raw: v };
  return { label: humanize(v), tone: 'muted', raw: v };
}

